import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import bank from "../src/data/bank.json";
import meta from "../src/data/meta.json";
import { OBJECTIVES } from "../src/data/objectives";
import { SOURCES } from "../src/data/sources";
import { ALLOC_MOCK, BANK_TARGET, DOMAINS, LETTERS, type BankFile, type MetaFile } from "../src/lib/types";
import { validateBankFile } from "../src/lib/validate";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const B = bank as unknown as BankFile;
const M = meta as unknown as MetaFile;
const errors: string[] = [];
const warns: string[] = [];

const r = validateBankFile(B);
errors.push(...r.errors);

const norm = (s: string) => s.toLowerCase().replace(/[^a-z0-9 ]+/g, " ").replace(/\s+/g, " ").trim();
const grams = (s: string) => {
  const w = norm(s).split(" ");
  const g = new Set<string>();
  for (let i = 0; i + 2 < w.length; i++) g.add(w.slice(i, i + 3).join(" "));
  return g;
};
const jac = (a: Set<string>, b: Set<string>) => {
  let i = 0;
  for (const x of a) if (b.has(x)) i++;
  return i / (a.size + b.size - i || 1);
};

const seenText = new Map<string, number>();
const G = B.questions.map((q) => grams(q.scenario_question));
B.questions.forEach((q, i) => {
  const k = norm(q.scenario_question);
  if (seenText.has(k)) errors.push(`exact duplicate scenario: ${q.id} = ${seenText.get(k)}`);
  seenText.set(k, q.id);
  if (!M[String(q.id)]) errors.push(`missing meta for ${q.id}`);
  for (let j = 0; j < i; j++) {
    const s = jac(G[i], G[j]);
    if (s > 0.35) warns.push(`near-duplicate scenarios ${B.questions[j].id}/${q.id} (jaccard ${s.toFixed(2)})`);
  }
  // hint must not contain the correct option text verbatim
  const c = q.options.find((o) => o.is_correct)!;
  if (norm(q.hint).includes(norm(c.text)) && norm(c.text).length > 12) errors.push(`hint reveals answer in ${q.id}`);
  for (const o of q.options) if (/\boption [a-d]\b/i.test(o.business_rationale)) warns.push(`rationale refers to a letter in ${q.id}`);
});

// per-domain counts
const per = Object.fromEntries(DOMAINS.map((d) => [d, B.questions.filter((q) => q.exam_domain === d).length]));
// mocks
const mockInfo: string[] = [];
for (const n of [1, 2, 3] as const) {
  const have = Object.fromEntries(DOMAINS.map((d) => [d, B.questions.filter((q) => q.exam_domain === d && M[String(q.id)]?.mock === n).length]));
  const total = Object.values(have).reduce((a, b) => a + b, 0);
  const full = DOMAINS.every((d) => have[d] === ALLOC_MOCK[d]);
  mockInfo.push(`Mock ${n}: ${total}/60 (${DOMAINS.map((d) => `${have[d]}/${ALLOC_MOCK[d]}`).join(" · ")}) ${full ? "COMPLETE" : "INCOMPLETE"}`);
}
// answer position balance & length bias
const pos: Record<string, number> = { A: 0, B: 0, C: 0, D: 0 };
let longest = 0, shortest = 0, lenDiff = 0;
for (const q of B.questions) {
  const c = q.options.find((o) => o.is_correct)!;
  pos[c.option_letter]++;
  const lens = q.options.map((o) => o.text.length);
  if (c.text.length === Math.max(...lens)) longest++;
  if (c.text.length === Math.min(...lens)) shortest++;
  lenDiff += c.text.length - lens.filter((_, i) => !q.options[i].is_correct).reduce((a, b) => a + b, 0) / 3;
}
const n = B.questions.length || 1;
for (const L of LETTERS) if (n >= 20 && (pos[L] / n < 0.2 || pos[L] / n > 0.3)) warns.push(`answer position ${L} is ${(100 * pos[L] / n).toFixed(0)}%`);
if (n >= 20 && shortest / n > 0.45) warns.push(`correct answer is the shortest option in ${(100 * shortest / n).toFixed(0)}% of questions`);
if (n >= 20 && longest / n > 0.4) warns.push(`correct answer is the longest option in ${(100 * longest / n).toFixed(0)}% of questions`);

// objective coverage
const objCount: Record<string, number> = {};
for (const q of B.questions) {
  const o = M[String(q.id)]?.objective;
  objCount[o] = (objCount[o] ?? 0) + 1;
  if (!OBJECTIVES.some((x) => x.id === o)) errors.push(`unknown objective ${o} on ${q.id}`);
}
for (const o of OBJECTIVES) if (!objCount[o.id]) warns.push(`objective ${o.id} has no questions`);
// sources
const noSrc = B.questions.filter((q) => (M[String(q.id)]?.source_ids ?? []).length === 0).length;
for (const q of B.questions) for (const s of M[String(q.id)]?.source_ids ?? []) if (!SOURCES.some((x) => x.id === s)) errors.push(`unknown source ${s} on ${q.id}`);
const verified = B.questions.filter((q) => M[String(q.id)]?.verification_date).length;

const lines: string[] = [];
lines.push("# Coverage report", "", `Generated by \`npm run bank:validate\`. **Content is DRAFT and UNVERIFIED** (see README, "What was verified").`, "");
lines.push(`Questions authored: **${B.questions.length} of 360 target**`, "", "| Domain | Authored | Target |", "|---|---|---|");
for (const d of DOMAINS) lines.push(`| ${d} | ${per[d]} | ${BANK_TARGET[d]} |`);
lines.push("", "## Mocks", "", ...mockInfo.map((x) => `- ${x}`), "");
lines.push("## Quality metrics", "", `- Correct-answer positions: ${LETTERS.map((L) => `${L} ${pos[L]}`).join(", ")}`, `- Correct option is the longest option in ${(100 * longest / n).toFixed(0)}% of questions (random expectation ≈ 25%), the shortest in ${(100 * shortest / n).toFixed(0)}%`, `- Mean length difference, correct vs. average distractor: ${(lenDiff / n).toFixed(1)} characters`, `- Questions with a source id: ${B.questions.length - noSrc}; without: ${noSrc}`, `- Questions verified against a source: ${verified}`, "");
lines.push("## Objective coverage (app-defined objectives, NOT official IDs)", "", "| Objective | Domain | Title | Questions |", "|---|---|---|---|");
for (const o of OBJECTIVES) lines.push(`| ${o.id} | ${o.domain} | ${o.title} | ${objCount[o.id] ?? 0} |`);
lines.push("", `## Warnings (${warns.length})`, "", ...(warns.length ? warns.map((w) => `- ${w}`) : ["None."]), "", `## Errors (${errors.length})`, "", ...(errors.length ? errors.map((w) => `- ${w}`) : ["None."]), "");
mkdirSync(join(root, "docs"), { recursive: true });
writeFileSync(join(root, "docs/COVERAGE.md"), lines.join("\n"));

const src = ["# Source register", "", "Status reflects what this build actually managed to read on 2026-10-13.", "", "| ID | Title | URL | Status | Note |", "|---|---|---|---|---|", ...SOURCES.map((s) => `| ${s.id} | ${s.title} | ${s.url} | ${s.status} | ${s.note} |`), ""];
writeFileSync(join(root, "docs/SOURCES.md"), src.join("\n"));

console.log(`questions=${B.questions.length} errors=${errors.length} warnings=${warns.length}`);
console.log(mockInfo.join("\n"));
for (const e of errors) console.error("ERROR", e);
for (const w of warns.slice(0, 40)) console.warn("WARN", w);
process.exit(errors.length ? 1 : 0);
